const assert = require("assert");
const matchmaker = require("../lib/rankedMatchmaker");
const battleQueue = require("../lib/rankedBattleQueue");
const fs = require("fs");
const os = require("os");
const path = require("path");
const team = (base) => [0,1,2].map((i) => ({ caughtAt:base+i, dexId:25+i, displayName:`Mon${base+i}`, level:20+i }));
const queue = { entries:{ a:{userId:"a",display:"Alpha",joinedAt:1,team:team(10)}, b:{userId:"b",display:"Beta",joinedAt:2,team:team(20)} } };
const profiles = { users:{ a:{ranked:{}}, b:{ranked:{}} } };
assert.equal(matchmaker.pairOldest(queue,"b")[0].userId,"a");
const match = matchmaker.startIfReady({queue,joiningUserId:"b",profiles,now:12345});
assert.ok(match?.winnerUserId);
assert.equal(queue.entries.a.status,"battling");
assert.equal(queue.entries.b.status,"battling");
assert.equal(profiles.users.a.ranked.games,undefined);
assert.equal(profiles.users.b.ranked.games,undefined);
assert.equal(match.players[0].team.length,3);
const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "ranked-battle-"));
const queueFile = path.join(tempDir, "queue.json");
const readJson = (file, fallback) => fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : fallback;
battleQueue.enqueue(queueFile, readJson, match);
const claimed = battleQueue.claimNext(queueFile, readJson);
assert.equal(claimed.id, match.id);
assert.equal(claimed.status, "playing");
assert.equal(battleQueue.claimNext(queueFile, readJson).id, match.id);
assert.equal(battleQueue.complete(queueFile, readJson, match.id).alreadyCompleted, false);
matchmaker.finalize(match, profiles);
assert.equal(profiles.users.a.ranked.games,1);
assert.equal(profiles.users.b.ranked.games,1);
assert.equal(battleQueue.complete(queueFile, readJson, match.id).alreadyCompleted, true);
console.log("Ranked-Matchmaker, Overlay-Queue und einmaliger Kampfabschluss: OK");
