const assert = require("assert");
const lab = require("../widget/battle-lab.js");
const natures = require("../lib/natures");

assert.equal(natures.parseNature("Mäßig").id, "modest");
assert.equal(natures.parseNature("massig").id, "modest");
assert.equal(natures.parseNature("ADAMANT").id, "adamant");
assert.equal(natures.calculateStats({hp:78,attack:84,defense:78,specialAttack:109,specialDefense:85,speed:100},50,"timid").speed, 132);
assert.equal(lab.effectiveness("electric",["ground"]),0);
const first=lab.simulate({seed:42}), second=lab.simulate({seed:42});
assert.deepEqual(first.log,second.log);
assert.ok(first.log.some((entry)=>entry.text.includes("Schaden")));
assert.ok(first.log.length<500);
for(let i=1;i<first.log.length;i++) assert.ok(!(first.log[i-1].turn===first.log[i].turn&&first.log[i-1].text.includes("schickt")&&first.log[i].text.includes("ausgewechselt")),"Kein erzwungener Doppelwechsel im selben Zug");
const immunity=lab.simulate({seed:1002,teamA:["pikachu","snorlax","venusaur"],teamB:["blastoise","lapras","rhydon"]});
assert.ok(immunity.log.some(entry=>entry.text.includes("keine Wirkung auf Rizeros")),"Elektro-Immunität wird protokolliert");
assert.ok(!immunity.log.some(entry=>/Donnerblitz.*: [1-9]/.test(entry.text)&&entry.text.includes("Rizeros")),"Immunitäten verursachen exakt 0 Schaden");
assert.ok(immunity.log.some(entry=>entry.text.includes("Pikachu wird gegen Bisaflor ausgewechselt")),"Pikachu bleibt nicht wirkungslos gegen Rizeros stehen");
const fastAttackers=lab.simulate({seed:1004,teamA:["alakazam","jolteon","gengar"],teamB:["charizard","dragonite","machamp"]});
assert.equal(fastAttackers.log.filter(entry=>entry.turn<=2&&entry.text.includes("Simsala setzt Psychokinese ein")).length,2,"Simsala nutzt freien Schaden gegen Glurak");
assert.ok(fastAttackers.log.some(entry=>entry.text.includes("Dragoran setzt Erdbeben ein")&&entry.text.includes("sehr effektiv")),"Dragoran erkennt Erdbeben gegen Gengar");
console.log("Wesen, Kampfphasen, Immunitäten, Wechselkosten und reproduzierbare 3-gegen-3-Simulation: OK");
